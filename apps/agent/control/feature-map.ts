import { readFileSync, writeFileSync } from "node:fs";
import nodePath from "node:path";

import { edgeRoutes } from "../src/edge/routes.ts";
import { agentRoot } from "./workspace.ts";

export const featureMapPath = nodePath.join(
  agentRoot,
  "..",
  "..",
  "docs",
  "verification",
  "agent-feature-map.md"
);

const routeRows = edgeRoutes.map(
  (route) =>
    `| \`${route.method} ${route.path}\` | ${route.access} | ${route.purpose} |`
);

export const renderFeatureMap = () =>
  [
    "# Feature Map: apps/agent",
    "",
    "Generated from `apps/agent/src/edge/routes.ts` by `pnpm control map`. Do not edit this file. `pnpm control map --check` fails when it is out of date.",
    "",
    "| Route | Access | Purpose |",
    "| --- | --- | --- |",
    ...routeRows,
    "",
    "## Seed and navigation",
    "",
    "1. Run `pnpm control dev`. It applies the Directory migrations to local D1 and starts the Worker with a fake Telegram API and a fake model.",
    "2. Run `pnpm control owner add --telegram-user <id>` to seed the Owner through `POST /operator/owners`.",
    "3. Send a Telegram update to `POST /telegram/webhook` with the `TELEGRAM_WEBHOOK_SECRET` from `.dev.vars`. The `dev` output shows the fake `sendMessage` reply.",
    "",
    "`pnpm control request --contains <text>` runs steps 1 to 3 with temporary storage and checks the reply.",
    "",
  ].join("\n");

export const featureMapIsCurrent = () =>
  readFileSync(featureMapPath, "utf-8") === renderFeatureMap();

export const writeFeatureMap = () => {
  writeFileSync(featureMapPath, renderFeatureMap());
};
