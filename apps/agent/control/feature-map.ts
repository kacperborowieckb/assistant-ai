import { readFileSync, writeFileSync } from "node:fs";
import nodePath from "node:path";

import { edgeRoutes } from "../src/edge/routes.ts";
import { agentRoot } from "./workspace.ts";

export const featureMapPath = nodePath.join(
  agentRoot,
  "..",
  "..",
  "docs",
  "verification",
  "agent-feature-map.md"
);

const routeRows = edgeRoutes.map(
  (route) =>
    `| \`${route.method} ${route.path}\` | ${route.access} | ${route.purpose} |`
);

export const renderFeatureMap = () =>
  [
    "# Feature Map: apps/agent",
    "",
    "Generated from `apps/agent/src/edge/routes.ts` by `pnpm control map`. Do not edit this file. `pnpm control map --check` fails when it is out of date.",
    "",
    "| Route | Access | Purpose |",
    "| --- | --- | --- |",
    ...routeRows,
    "",
    "## Seed and navigation",
    "",
    "1. Run `pnpm control dev`. It applies the Directory migrations to local D1 and starts the Worker with a fake Telegram API and a fake model.",
    "2. Run `pnpm control owner add --telegram-user <id>` to seed the Owner through `POST /operator/owners`.",
    "3. Send a Telegram update to `POST /telegram/webhook` with the `TELEGRAM_WEBHOOK_SECRET` from `.dev.vars`. The `dev` output shows the fake `sendMessage` reply.",
    "",
    "`pnpm control request --contains <text>` runs steps 1 to 3 with temporary storage and checks the reply.",
    "",
    "## Schedules in the chat",
    "",
    'The Owner sets, lists, changes, and cancels Schedules (Reminders, with the `SendText` Action, and Scheduled Tasks, with the `RunPrompt` Action) through the Telegram webhook, with the tools `set_schedule`, `list_schedules`, `change_schedule`, and `cancel_schedule`. In the local fake model, a message that starts with `zone: <IANA name>` sets the time zone, `remind: <text>` sets a Reminder for the next minute, `remind daily: <text>` sets a Daily repeating Reminder for the next minute (it stays active and moves to the next day after it is sent), `task: <prompt>` sets a Scheduled Task for the next minute, `task daily: <prompt>` sets a Daily repeating Scheduled Task (the fake model answers its Turn with `Scheduled task result: <prompt>`), and `cancel reminder: <words>` lists the Reminders and cancels the first one that contains the words. Example: `pnpm control request --message "zone: Europe/Warsaw" --message "remind: buy the gift" --message "cancel reminder: buy the gift" --contains "Cancelled Reminder: buy the gift" --wait-for-later-message`. Scheduled Task example: `pnpm control request --message "zone: Europe/Warsaw" --message "task: list my notes" --contains "Scheduled task result: list my notes" --wait-for-later-message`.',
    "",
  ].join("\n");

export const featureMapIsCurrent = () =>
  readFileSync(featureMapPath, "utf-8") === renderFeatureMap();

export const writeFeatureMap = () => {
  writeFileSync(featureMapPath, renderFeatureMap());
};
