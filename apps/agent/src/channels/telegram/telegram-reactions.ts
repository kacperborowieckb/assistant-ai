const variationsAndSkinTones =
  /\u{FE0E}|\u{FE0F}|\u{1F3FB}|\u{1F3FC}|\u{1F3FD}|\u{1F3FE}|\u{1F3FF}/gu;

const plainEmoji = (emoji: string) =>
  emoji.trim().replaceAll(variationsAndSkinTones, "");

export const telegramReactionFor = (emoji: string): string | undefined => {
  const plain = plainEmoji(emoji);
  if (telegramReactions.has(plain)) {
    return plain;
  }
  return telegramCloseMatches.get(plain);
};
